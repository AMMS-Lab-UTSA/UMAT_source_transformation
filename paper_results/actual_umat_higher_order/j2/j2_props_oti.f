         WRITE(IOTIHJ,*)OTI_I,2,6,6,GETIM(STRESS_OTI(OTI_I),27)*2.0D0
         WRITE(IOTIHJ,*)OTI_I,3,1,1,1,GETIM(STRESS_OTI(OTI_I),28)*6.0D0
         WRITE(IOTIHJ,*)OTI_I,3,1,1,2,GETIM(STRESS_OTI(OTI_I),29)*2.0D0
         WRITE(IOTIHJ,*)OTI_I,3,1,1,3,GETIM(STRESS_OTI(OTI_I),32)*2.0D0
