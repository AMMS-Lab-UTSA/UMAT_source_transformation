         WRITE(IOTIHJ,*)OTI_I,2,2,2,GETIM(STRESS_OTI(OTI_I),9)*2.0D0
         WRITE(IOTIHJ,*)OTI_I,2,2,3,GETIM(STRESS_OTI(OTI_I),11)
         WRITE(IOTIHJ,*)OTI_I,2,2,4,GETIM(STRESS_OTI(OTI_I),14)
