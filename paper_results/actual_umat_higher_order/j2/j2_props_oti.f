         WRITE(IOTIHJ,*)OTI_I,2,1,3,GETIM(STRESS_OTI(OTI_I),10)
         WRITE(IOTIHJ,*)OTI_I,2,1,4,GETIM(STRESS_OTI(OTI_I),13)
         WRITE(IOTIHJ,*)OTI_I,2,1,5,GETIM(STRESS_OTI(OTI_I),17)
