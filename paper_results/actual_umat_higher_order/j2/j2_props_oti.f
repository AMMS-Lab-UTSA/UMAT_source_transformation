         WRITE(IOTIHJ,*)OTI_I,2,3,3,GETIM(STRESS_OTI(OTI_I),12)*2.0D0
         WRITE(IOTIHJ,*)OTI_I,2,3,4,GETIM(STRESS_OTI(OTI_I),15)
         WRITE(IOTIHJ,*)OTI_I,2,3,5,GETIM(STRESS_OTI(OTI_I),19)
