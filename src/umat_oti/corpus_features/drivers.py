def _row(values) -> str:
    return " ".join(repr(float(v)) for v in values)


@dataclass
class RunConfig:
    ntens: int
    nstatv: int
    nprops: int
    ndi: int
    nshr: int
    props: list
    statev0: list
    cmname: str
    increments: list           # [(dstran, f0, f1, drot, dtime, temp, dtemp)]
    coords: tuple = (0.0, 0.0, 0.0)
    call_sdvini: bool = False

    def write(self, directory: Path) -> Path:
        path = Path(directory) / CONFIG_FILE
        lines = [f"{self.ntens} {self.nstatv} {self.nprops} {self.ndi} {self.nshr} "
                 f"{len(self.increments)} {1 if self.call_sdvini else 0}",
                 (self.cmname or "MATERIAL")[:80],
                 _row(self.props if self.props else [0.0]),
                 _row(self.statev0 if self.statev0 else [0.0] * max(self.nstatv, 1)),
                 _row(self.coords)]
        for dstran, f0, f1, drot, dtime, temp, dtemp in self.increments:
            lines.append(_row([dtime, temp, dtemp]))
            lines.append(_row(dstran))
            lines.append(_row(np.asarray(f0).reshape(-1)))
            lines.append(_row(np.asarray(f1).reshape(-1)))
            lines.append(_row(np.asarray(drot).reshape(-1)))
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path


@dataclass
class Perturbation:
    mode: str                  # "local" | "total"
    kind: str                  # props|statev|dstran|dfgrd1|stress
    index: int                 # 1-based (0 for dfgrd1)
    step: float                # absolute
    direction: tuple = ((0, 0, 0), (0, 0, 0), (0, 0, 0))   # strain direction for dfgrd1


def write_perturbations(directory: Path, perturbations: Sequence[Perturbation]) -> Path:
    path = Path(directory) / PERT_FILE
    lines = [str(len(perturbations))]
    for p in perturbations:
        lines.append(f"{1 if p.mode == 'local' else 2} {KIND[p.kind]} {int(p.index)} "
                     f"{float(p.step)!r} " + _row(np.asarray(p.direction, float).reshape(-1)))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


@dataclass
class Seed:
    kind: str
    index: int
    direction: int             # 1-based OTI imaginary direction
    strain: tuple = ((0, 0, 0), (0, 0, 0), (0, 0, 0))


def write_seeds(directory: Path, mode: str, seeds: Sequence[Seed]) -> Path:
    path = Path(directory) / SEED_FILE
    lines = [f"{1 if mode == 'local' else 2} {len(seeds)}"]
    for s in seeds:
        lines.append(f"{KIND[s.kind]} {int(s.index)} {int(s.direction)} "
                     + _row(np.asarray(s.strain, float).reshape(-1)))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


