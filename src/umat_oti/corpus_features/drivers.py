def quadify(text: str) -> str:
    """The ORIGINAL with its double precision promoted to REAL(16).

    Every REAL*8 / DOUBLE PRECISION / REAL(8) / REAL(KIND=8) (declarations and
    IMPLICIT statements) becomes REAL*16; D-prefixed specific intrinsics
    become generic; DBLE becomes QEXT. Default REAL (binary32) declarations
    and every literal are left exactly as written, so the author's binary32
    quantities stay binary32 and every constant keeps the value the double
    build gives it: the quad build evaluates the same function (Curie-G B2,
    scripts/quadfd.py) with less rounding. A source whose real kind comes
    from a named constant (``REAL(dp)``) is NOT promoted; the primal check
    against the double build is what refuses such a reference.
    """
    t = re.sub(r"(?i)\bdouble\s+precision\b", "REAL*16", text)
    t = re.sub(r"(?i)\breal\s*\*\s*8\b", "REAL*16", t)
    t = re.sub(r"(?i)\breal\s*\(\s*(kind\s*=\s*)?8\s*\)", "REAL(16)", t)
    t = re.sub(r"(?i)\bD(SQRT|EXP|LOG|LOG10|ABS|SIN|COS|TAN|ASIN|ACOS|ATAN|ATAN2|SINH|COSH|TANH|"
               r"SIGN|MOD|MAX1|MIN1|DIM)\s*\(", lambda m: m.group(1) + "(", t)
    t = re.sub(r"(?i)\bDBLE\s*\(", "QEXT(", t)
    return t


def quad_driver(stubs: str, sdvini: bool) -> str:
    """REAL_DRIVER with the routine's state in REAL(16).

    Inputs (configuration, steps, directions) stay REAL(8) and are converted
    exactly; the perturbed input is formed in REAL(16) (x + h exact). Besides
    the usual records it writes ``l``/``t``: perturbed minus base output,
    differenced in REAL(16) before rounding to text.
    """
    src = REAL_DRIVER
    quad_lines = [
        "  REAL(8), ALLOCATABLE :: STRESS(:),STATEV(:),DDSDDE(:,:),STRAN(:),DSTRAN(:)",
        "  REAL(8), ALLOCATABLE :: PROPS(:),DDSDDT(:),DRPLDE(:)",
        "  REAL(8), ALLOCATABLE :: S_IN(:),X_IN(:),STRAN_IN(:),SB(:),XB(:)",
        "  REAL(8) :: SSE,SPD,SCD,RPL,DRPLDT,PNEWDT,CELENT,DTIME,TEMP,DTEMP",
        "  REAL(8) :: SSE_IN,SPD_IN,SCD_IN,SSEB,SPDB,SCDB",
        "  REAL(8) :: TIME(2),TIME_IN(2),PREDEF(1),DPRED(1),COORDS(3),DROT(3,3)"]
    for line in quad_lines:
        assert line in src, line
        src = src.replace(line, line.replace("REAL(8)", "REAL(16)"))
    old = "  REAL(8) :: DFGRD0(3,3),DFGRD1(3,3),ZDIR(3,3)"
    assert old in src
    src = src.replace(old, "  REAL(16) :: DFGRD0(3,3),DFGRD1(3,3)\n  REAL(8) :: ZDIR(3,3)\n"
                           "  REAL(16), ALLOCATABLE :: BS(:,:),BX(:,:)")
    old = "  ALLOCATE(DDSDDT(NTENS),DRPLDE(NTENS))\n"
    assert old in src
    src = src.replace(old, old + "  ALLOCATE(BS(NTENS,NINC),BX(MAX(NSTATV,1),NINC))\n")
    old = "    SB=STRESS; XB=STATEV; SSEB=SSE; SPDB=SPD; SCDB=SCD\n"
    assert old in src
    src = src.replace(old, old + "    BS(:,INC)=STRESS; BX(:,INC)=STATEV\n")
    old = """        WRITE(UO,'(A,3(1X,I0),*(1X,ES25.16E3))') 'L',INC,IP,SG,(STRESS(I),I=1,NTENS), &
          (STATEV(I),I=1,MAX(NSTATV,1)),PNEWDT
"""
    assert old in src
    src = src.replace(old, old + """        WRITE(UO,'(A,3(1X,I0),*(1X,ES25.16E3))') 'l',INC,IP,SG,(STRESS(I)-SB(I),I=1,NTENS), &
          (STATEV(I)-XB(I),I=1,MAX(NSTATV,1))
""")
    old = """        WRITE(UO,'(A,3(1X,I0),*(1X,ES25.16E3))') 'T',IP,SG,INC,(STRESS(I),I=1,NTENS), &
          (STATEV(I),I=1,MAX(NSTATV,1)),PNEWDT
"""
    assert old in src
    src = src.replace(old, old + """        WRITE(UO,'(A,3(1X,I0),*(1X,ES25.16E3))') 't',IP,SG,INC,(STRESS(I)-BS(I,INC),I=1,NTENS), &
          (STATEV(I)-BX(I,INC),I=1,MAX(NSTATV,1))
""")
    return src.replace("PROGRAM cf_real_driver", "PROGRAM cf_quad_driver", 1).replace(
        "END PROGRAM cf_real_driver", "END PROGRAM cf_quad_driver")


