@dataclass
class Build:
    program: Optional[Path] = None
    ok: bool = False
    reason: str = ""
    log: str = ""
    command: list = field(default_factory=list)

    def as_dict(self) -> dict:
        return {"program": str(self.program) if self.program else None, "ok": self.ok,
                "reason": self.reason, "log_tail": self.log[-1500:],
                "command": [str(c) for c in self.command]}


def _gfortran_form_flags(path: Path, text: str) -> list:
    from umat_oti.fortran.normalize import detect_source_form
    form = detect_source_form(path, text)
    if str(form).lower().startswith("free"):
        return ["-ffree-form", "-ffree-line-length-none"]
    return ["-ffixed-form", "-ffixed-line-length-none"]


def prepare_original_source(source: Path, work: Path) -> tuple:
    """Copy of the original with console writes silenced and the author's
    PROGRAM removed (both done by the corpus replay helpers, unchanged).
    Returns (prepared_path, text, form_flags)."""
    from umat_oti.abaqus.probe import silence_console_writes
    from umat_oti.abaqus.replay import _text_of, without_the_authors_program
    from umat_oti.fortran.normalize import detect_source_form

    text = _text_of(Path(source))
    form = detect_source_form(Path(source), text)
    text, _ = silence_console_writes(text, form)
    text, _ = without_the_authors_program(text, form)
    suffix = Path(source).suffix if Path(source).suffix.lower() in (".f", ".for", ".f90", ".f77") else ".f"
    prepared = Path(work) / f"original_umat{suffix}"
    prepared.write_text(text, encoding="utf-8")
    return prepared, text, _gfortran_form_flags(Path(source), text)


def stub_block(source_text: str) -> str:
    from umat_oti.abaqus.replay import _replay_utility_stubs
    from umat_oti.abaqus.single_call import drop_stubs_defined_by
    from umat_oti.validation.actual_umat_higher_order_generic import _abaqus_utility_stubs
    stubs, _ = drop_stubs_defined_by(_abaqus_utility_stubs() + _replay_utility_stubs(),
                                     source_text)
    return stubs


def build_real(work: Path, units: Sequence[Path], source_text: str, *,
               objects: Sequence[Path] = (), module_dirs: Sequence[Path] = (),
               sdvini: bool = False, unit_flags: Sequence[Sequence[str]] = (),
               compiler: str = "gfortran", opt: str = "-O0",
               extra_flags: Sequence[str] = (), quad: bool = False) -> Build:
    """Compile ``units`` (each with its own form flags) + the real driver.

    ``extra_flags`` go on every unit (the hidden-state gate's variants:
    ``-finit-real=snan ...`` / ``-finit-real=zero ...`` / ``-fcheck=bounds``).
    """
    from umat_oti.abaqus.single_call import install_headers
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    if shutil.which(compiler) is None:
        return Build(reason=f"{compiler} not on PATH")
    install_headers(work)
    if quad:
        # the header's documented content, promoted with the source
        for name in ("aba_param.inc", "ABA_PARAM.INC", "aba_param.INC", "ABA_PARAM.inc"):
            (work / name).write_text("      implicit real*16(a-h,o-z)\n"
                                     "      parameter (nprecd=2)\n", encoding="utf-8")
    elif not any((work / n).is_file() for n in ("aba_param.inc", "ABA_PARAM.INC")):
        # No Abaqus installation: the header's documented content.
        for name in ("aba_param.inc", "ABA_PARAM.INC", "aba_param.INC", "ABA_PARAM.inc"):
            (work / name).write_text("      implicit real*8(a-h,o-z)\n"
                                     "      parameter (nprecd=2)\n", encoding="utf-8")
    driver = work / "cf_real_driver.f90"
    template = quad_driver("", sdvini) if quad else REAL_DRIVER
    stubs = stub_block(source_text)
    driver.write_text(template % {
        "common": _COMMON_DECL, "read": _READ_CONFIG % {"config": CONFIG_FILE},
        "pert": PERT_FILE, "out": REAL_OUT, "sdvini": _SDVINI if sdvini else "    CONTINUE",
        "stubs": quadify(stubs) if quad else stubs}, encoding="utf-8")
    includes = [f"-I{work}"] + [f"-I{d}" for d in module_dirs]
    objs = []
    log = ""
    for k, unit in enumerate(units):
        flags = list(unit_flags[k]) if k < len(unit_flags) else []
        obj = work / f"cf_unit_{k}.o"
        cmd = [compiler, opt, "-std=legacy", *flags, *extra_flags, *includes, "-c", str(unit),
               "-o", str(obj), f"-J{work}"]
        done = subprocess.run(cmd, cwd=work, capture_output=True, text=True)
        log += done.stdout + done.stderr
        if done.returncode != 0:
            return Build(reason=f"compile of {Path(unit).name} failed (exit {done.returncode})",
                         log=log, command=cmd)
        objs.append(obj)
    program = work / "cf_real_driver"
    cmd = [compiler, opt, "-ffree-line-length-none", *includes, str(driver), *map(str, objs),
           *map(str, objects), "-o", str(program)]
    done = subprocess.run(cmd, cwd=work, capture_output=True, text=True)
    log += done.stdout + done.stderr
    if done.returncode != 0 or not program.is_file():
        return Build(reason=f"driver link failed (exit {done.returncode})", log=log, command=cmd)
    return Build(program=program, ok=True, log=log, command=cmd)


def run_program(build: Build, work: Path, timeout: int = 1800) -> tuple:
    if not build.ok:
        return False, build.reason
    try:
        done = subprocess.run([str(build.program)], cwd=str(work), capture_output=True,
                              text=True, timeout=timeout, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError) as error:
        return False, f"{type(error).__name__}: {error}"
    if done.returncode != 0:
        return False, f"exit {done.returncode}: {(done.stdout + done.stderr)[-1500:]}"
    return True, (done.stdout + done.stderr)[-500:]


def kstep_rank(lifted_source: str) -> int:
    """Rank of the 36th dummy (KSTEP slot) of ``umat_oti`` in a lifted source.

    Some corpus sources declare that slot as ``JSTEP(4)``. A legacy call with
    a scalar works by accident; a module procedure with an explicit interface
    refuses it, so the driver has to pass an array exactly when the routine
    declares one.
    """
    match = re.search(r"subroutine\s+umat_oti\s*\(([^)]*)\)", lifted_source, re.IGNORECASE)
    if not match:
        return 0
    dummies = [d.strip() for d in match.group(1).replace("&", " ").split(",")]
    if len(dummies) < 36:
        return 0
    name = dummies[35]
    body = lifted_source[match.end():]
    end = re.search(r"end\s+subroutine\s+umat_oti", body, re.IGNORECASE)
    body = body[:end.start()] if end else body
    if re.search(rf"(?<![\w%]){re.escape(name)}\s*\(", body, re.IGNORECASE):
        return 1
    return 0


def build_oti(work: Path, lifted_dir: Path, module: str, type_name: str, ndir: int, *,
              compiler: str = "gfortran", kstep_rank: int = 0) -> Build:
    """Compile the run-time-seeded OTI driver against a lifted build's objects."""
    work = Path(work)
    driver = Path(lifted_dir) / "cf_oti_driver.f90"
    source = OTI_DRIVER % {
        "module": module, "type": type_name, "common": _COMMON_DECL,
        "read": _READ_CONFIG % {"config": CONFIG_FILE}, "seeds": SEED_FILE,
        "out": OTI_OUT, "ndir": ndir}
    if kstep_rank:
        source = source.replace("INTEGER :: NOEL,NPT,LAYER,KSPT,KSTEP,KINC",
                                "INTEGER :: NOEL,NPT,LAYER,KSPT,KSTEP(4),KINC")
        source = source.replace("KSTEP=1; KINC=INC", "KSTEP=0; KSTEP(1)=1; KINC=INC")
    driver.write_text(source, encoding="utf-8")
    objs = [Path(lifted_dir) / name for name in (
        "master_parameters.o", "real_utils.o", f"{module}.o", "oti_intrinsics.o",
        "umat_oti_lifted.o", "abaqus_stubs.o")]
    missing = [o.name for o in objs if not o.is_file()]
    if missing:
        return Build(reason=f"lifted build is missing {missing}")
    program = Path(lifted_dir) / "cf_oti_driver"
    cmd = [compiler, "-O1", "-std=legacy", "-ffree-line-length-none", f"-I{lifted_dir}",
           str(driver), *map(str, objs), "-o", str(program)]
    done = subprocess.run(cmd, cwd=lifted_dir, capture_output=True, text=True)
    if done.returncode != 0 or not program.is_file():
        return Build(reason=f"OTI driver link failed (exit {done.returncode})",
                     log=done.stdout + done.stderr, command=cmd)
    return Build(program=program, ok=True, log=done.stdout + done.stderr, command=cmd)
