"""Routine-level drivers for corpus UMATs: original (real) and OTI (lifted).

Two Fortran programs, both generated here, both reading the same plain-text
configuration (``cf_config.txt``) so the original routine and the OTI build see
byte-identical inputs.

``cf_real_driver``
    Calls a routine with the STANDARD Abaqus interface (all REAL(8)). Linked
    either against the ORIGINAL source (the reference) or against the store's
    DSTRAN-seeded OTI build, whose interface is also real (it returns DDSDDE).
    In one process it runs

    * the base history, increment by increment (``B`` records),
    * LOCAL perturbations: at every increment, for every requested
      perturbation and sign, one call from the RESTORED incoming state --
      STRESS, STATEV, STRAN, SSE/SPD/SCD, TIME copied back from the base
      trajectory; DDSDDE, DDSDDT, DRPLDE, RPL, DRPLDT zeroed; PNEWDT = 1 --
      (``L`` records),
    * TOTAL perturbations: the whole history re-run from the initial state
      with the perturbation applied (``T`` records).

``cf_oti_driver``
    Calls ``umat_oti`` from the generically lifted build (every REAL argument
    is an OTI number). Seeds are read at run time: PROPS(i), incoming
    STATEV(i), incoming STRESS(i), DSTRAN(j) or a DFGRD1 direction, each onto
    one imaginary direction. Two modes:

    * ``local``: at every increment the incoming state is REAL (the previous
      increment's real parts), the seeds are applied, and the imaginary parts
      of STRESS/STATEV after the call are the LOCAL derivatives.
    * ``total``: PROPS seeds (or initial-STATEV seeds) are applied at the
      start and the OTI STRESS/STATEV are CARRIED across increments, so the
      imaginary parts at increment n are the TOTAL derivatives through the
      prescribed-strain history.
"""
