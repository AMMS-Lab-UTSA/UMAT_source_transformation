@dataclass
class RealOutput:
    initial_statev: np.ndarray
    base: dict = field(default_factory=dict)      # inc -> dict(stress, statev, ddsdde, sse, spd, scd, pnewdt)
    local: dict = field(default_factory=dict)     # (inc, ip, sign) -> (stress, statev, pnewdt)
    total: dict = field(default_factory=dict)     # (ip, sign, inc) -> (stress, statev, pnewdt)
    #: hidden-state gate records, all fields like ``base``:
    replay: dict = field(default_factory=dict)        # inc -> unperturbed call after the local block
    total_replay: dict = field(default_factory=dict)  # ip -> increment-1 call after total block ip
    zero_total: dict = field(default_factory=dict)    # inc -> h=0 total re-run at the end
    #: quad driver only: perturbed minus base output, differenced in REAL(16)
    #: and rounded once -- full relative precision of the difference itself
    local_delta: dict = field(default_factory=dict)   # (inc, ip, sign) -> (dstress, dstatev)
    total_delta: dict = field(default_factory=dict)   # (ip, sign, inc) -> (dstress, dstatev)


def _floats(tokens):
    out = []
    for t in tokens:
        try:
            out.append(float(t))
        except ValueError:            # Fortran writes e.g. 1.0-310 without the E
            m = re.match(r"^([-+]?\d*\.?\d+)([-+]\d+)$", t)
            out.append(float(f"{m.group(1)}e{m.group(2)}") if m else float("nan"))
    return np.array(out)


def parse_real_output(path: Path, ntens: int, nstatv: int) -> RealOutput:
    nx = max(nstatv, 1)
    result = RealOutput(initial_statev=np.zeros(nx))
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if not parts:
            continue
        tag = parts[0]
        if tag == "I":
            result.initial_statev = _floats(parts[1:1 + nx])
        elif tag in ("B", "R", "Q", "Z"):
            inc = int(parts[1])
            v = _floats(parts[2:])
            o = 0
            stress = v[o:o + ntens]; o += ntens
            statev = v[o:o + nx]; o += nx
            ddsdde = v[o:o + ntens * ntens].reshape(ntens, ntens); o += ntens * ntens
            sse, spd, scd, pnewdt = v[o:o + 4]
            {"B": result.base, "R": result.replay, "Q": result.total_replay,
             "Z": result.zero_total}[tag][inc] = dict(
                stress=stress, statev=statev[:nstatv], ddsdde=ddsdde,
                sse=sse, spd=spd, scd=scd, pnewdt=pnewdt)
        elif tag in ("L", "T"):
            a, b, c = int(parts[1]), int(parts[2]), int(parts[3])
            v = _floats(parts[4:])
            entry = (v[:ntens], v[ntens:ntens + nx][:nstatv], v[ntens + nx])
            (result.local if tag == "L" else result.total)[(a, b, c)] = entry
        elif tag in ("l", "t"):        # quad driver: (perturbed - base) computed in REAL(16)
            a, b, c = int(parts[1]), int(parts[2]), int(parts[3])
            v = _floats(parts[4:])
            entry = (v[:ntens], v[ntens:ntens + nx][:nstatv])
            (result.local_delta if tag == "l" else result.total_delta)[(a, b, c)] = entry
    return result


@dataclass
class OtiOutput:
    base: dict = field(default_factory=dict)      # inc -> dict(stress, statev, ddsdde, ...)
    dstress: dict = field(default_factory=dict)   # inc -> (ntens, ndir)
    dstatev: dict = field(default_factory=dict)   # inc -> (nstatv, ndir)


def parse_oti_output(path: Path, ntens: int, nstatv: int, ndir: int) -> OtiOutput:
    nx = max(nstatv, 1)
    result = OtiOutput()
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "B":
            inc = int(parts[1]); v = _floats(parts[2:]); o = 0
            stress = v[o:o + ntens]; o += ntens
            statev = v[o:o + nx]; o += nx
            ddsdde = v[o:o + ntens * ntens].reshape(ntens, ntens); o += ntens * ntens
            sse, spd, scd, pnewdt = v[o:o + 4]
            result.base[inc] = dict(stress=stress, statev=statev[:nstatv], ddsdde=ddsdde,
                                    sse=sse, spd=spd, scd=scd, pnewdt=pnewdt)
        elif parts[0] == "D":
            inc = int(parts[1]); v = _floats(parts[2:])
            result.dstress[inc] = v[:ntens * ndir].reshape(ntens, ndir)
            result.dstatev[inc] = v[ntens * ndir:ntens * ndir + nx * ndir].reshape(nx, ndir)[:nstatv]
    return result


